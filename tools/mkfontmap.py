#!/usr/bin/env python3
"""mkfontmap.py -- the text screens' character map, from the game's own font.

  mkfontmap.py ROM OUT.inc OUT.lua

Tecmo Bowl's CHR is ROM (128K, MMC1's limit), so our screens cannot upload a
font; they borrow the game's. 4K CHR bank 11 holds it, laid out as ASCII for
the letters and digits (the team-select screen writes "INDIANAPOLIS" as
$49 $4E $44 ...). This checks every glyph we claim really is a glyph in the
ROM -- not blank, not a solid block -- and writes:
  OUT.inc   FONTMAP: 96 tile numbers for ASCII $20-$7F (text.s)
  OUT.lua   the reverse map, tile -> character, for the rigs' screen dumps
Anything unmapped draws as a space.
"""
import sys

FONT_BANK = 11
# character -> tile. Letters, digits and space are ASCII; the rest are what
# the font has: '!' at $21, ':' at $3A, a dash at $3B, and the chevrons the
# game's menus use as cursors.
MAP = {c: ord(c) for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!:"}
MAP.update({' ': 0x20, '-': 0x3B, '>': 0x14, '<': 0x15})

def main():
    rom_path, inc_path, lua_path = sys.argv[1:]
    d = open(rom_path, 'rb').read()
    prg = d[4] * 16384
    chr_ = d[16 + prg:]
    bank = chr_[FONT_BANK * 4096:(FONT_BANK + 1) * 4096]
    for c, t in MAP.items():
        px = bank[t * 16:t * 16 + 16]
        vals = set()
        for y in range(8):
            for x in range(8):
                vals.add(((px[y] >> (7 - x)) & 1) | (((px[8 + y] >> (7 - x)) & 1) << 1))
        if c == ' ':
            assert vals == {0}, "tile $20 is not blank"
        else:
            assert 0 in vals and len(vals) > 1, "tile ${:02X} for {!r} is not a glyph".format(t, c)
    with open(inc_path, 'w') as f:
        f.write("; fontmap.inc -- GENERATED by tools/mkfontmap.py, do not edit.\n")
        f.write("; Tile in CHR bank {} for each ASCII character $20-$7F.\n".format(FONT_BANK))
        f.write("FONTMAP:\n")
        for row in range(0x20, 0x80, 16):
            f.write("        .byte " + ",".join("${:02X}".format(MAP.get(chr(c), 0x20))
                                                for c in range(row, row + 16)) + "\n")
    with open(lua_path, 'w') as f:
        f.write("-- fontmap.lua -- GENERATED by tools/mkfontmap.py, do not edit.\n")
        f.write("-- Tile -> character for the text screens (CHR bank {}).\n".format(FONT_BANK))
        f.write("return {\n")
        for c, t in sorted(MAP.items(), key=lambda kv: kv[1]):
            f.write("  [0x{:02X}] = {!r},\n".format(t, c).replace("'", '"'))
        f.write("}\n")

if __name__ == '__main__':
    main()
